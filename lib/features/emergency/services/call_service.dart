// บริการโทรออกสายด่วนฉุกเฉิน (Emergency Call Service)
// รับผิดชอบการแปลงและทำความสะอาดเบอร์โทรศัพท์ไทยทุกรูปแบบให้ Compatible กับ OS:
//   - เบอร์ด่วนสั้น 3-4 หลัก (เช่น 1669, 1554, 191, 192)
//   - เบอร์มือถือ 10 หลัก (08x, 09x) → แปลงเป็น +66-8x...
//   - เบอร์บ้าน 9 หลัก (02x, 03x, ...) → แปลงเป็น +66-2x...
// จากนั้นเปิดแอปโทรศัพท์ของระบบปฏิบัติการผ่าน tel: URI Intent
// ============================================================================

import 'package:url_launcher/url_launcher.dart';
import 'package:flutter/foundation.dart';

/// 🏛️ คลาสบริการโทรออกสายด่วนฉุกเฉิน (CallService)
/// ทุกเมธอดเป็น static เพื่อให้เรียกใช้ได้ทันทีโดยไม่ต้องสร้างอินสแตนซ์
class CallService {
  /// 📌 เปิดแอปโทรศัพท์พร้อมพิมพ์เบอร์ปลายทาง โดยผ่านกระบวนการ Normalize เบอร์โทรไทยก่อนเสมอ
  /// - [phone]: เบอร์โทรศัพท์ในรูปแบบใดก็ได้ (เช่น '1669', '081-234-5678', '02-345-6789')
  static Future<void> makeCall(String phone) async {
    // 1. ตัดช่องว่างหัว-ท้าย และลบอักขระพิเศษ (-, (, ), .space)
    //    คงไว้เฉพาะตัวเลขและเครื่องหมาย + เพื่อป้องกันข้อผิดพลาดของ tel: URI
    String cleaned = phone.trim().replaceAll(RegExp(r'[^\d+]'), '');

    // 2. ตรวจสอบและแปลงรูปแบบเบอร์โทรไทยให้เข้ากับ E.164 International Format
    if (cleaned.length >= 3 &&
        cleaned.length <= 4 &&
        !cleaned.startsWith('+')) {
      // กรณี: เบอร์ด่วนสั้น 3-4 หลัก (1669, 1554, 191, 192, 195)
      // เพิ่ม +66 นำหน้า เพื่อป้องกัน OS บางรุ่น (locale อังกฤษ) แปลงเบอร์ผิดรูปแบบ
      cleaned = '+66$cleaned';
    } else if (cleaned.startsWith('0') &&
        (cleaned.length == 9 || cleaned.length == 10)) {
      // กรณี: เบอร์บ้าน (02x = 9 หลัก) หรือเบอร์มือถือ (08x/09x = 10 หลัก)
      // แทนที่เลข 0 นำหน้าด้วย +66 (รหัสประเทศไทย) ตามมาตรฐานสากล
      cleaned = '+66${cleaned.substring(1)}';
    }

    // 3. สร้าง URI รูปแบบ tel: สำหรับส่งคำขอเปิดแอปโทรศัพท์
    final Uri url = Uri.parse('tel:$cleaned');

    try {
      // 4. เปิดแอปโทรศัพท์ผ่าน OS Intent ด้วยโหมด platformDefault
      //    ให้ระบบปฏิบัติการจัดการ URI อย่างเหมาะสมกับแต่ละแพลตฟอร์ม (Android/iOS)
      final success = await launchUrl(url);
      if (!success) {
        debugPrint('CallService: ไม่สามารถเปิดแอปโทรศัพท์สำหรับเบอร์: $cleaned');
      }
    } catch (e) {
      debugPrint('CallService Error: $e');
    }
  }
}
